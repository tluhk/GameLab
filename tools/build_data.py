#!/usr/bin/env python3
"""Generate data/prompts.js from prompts/en.json and prompts/et.json.

The web page loads prompts as a script (not JSON) so it also works when
index.html is opened straight from a folder. Run this after editing the JSON files.
"""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
data = {}
for lang in ("en", "et"):
    with open(os.path.join(ROOT, "prompts", lang + ".json"), encoding="utf-8") as f:
        data[lang] = json.load(f)
with open(os.path.join(ROOT, "data", "prompts.js"), "w", encoding="utf-8") as f:
    f.write("// Generated by tools/build_data.py from prompts/*.json. Do not edit by hand.\n")
    f.write("window.MANGULABOR_PROMPTS = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")
print("wrote data/prompts.js")
